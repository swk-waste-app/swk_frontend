import { useEffect, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import { LuCalendarPlus, LuCamera, LuLightbulb, LuRefreshCw, LuScanLine, LuShoppingBag } from 'react-icons/lu';
import { toast } from 'sonner';
import { Badge, Button, Card, EmptyState, PageHeader } from '../../components/ui';
import { Skeleton } from '../../components/Skeleton';
import { apiAiStatus, apiClassifyWaste } from '../../services/ai';
import { SCHEDULE_PATH } from '../customerDashboard/pickupUtils';

const MARKETPLACE_PATH = '/customerDashboard/products';
const MAX_BYTES = 5 * 1024 * 1024;
const ACCEPTED_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'image/gif'];

const CONFIDENCE = {
  high: { tone: 'info', label: 'High confidence' },
  medium: { tone: 'neutral', label: 'Medium confidence' },
  low: { tone: 'warning', label: 'Low confidence' },
};

// The scanner writes its own messages: the server's are aimed at developers.
const scanError = (error) => {
  const code = error?.response?.status;
  if (!code) return 'No connection to the server. Check your internet and try again.';
  if (code === 429) return 'The scanner is busy. Try again in a minute.';
  if (code === 413 || code === 422) return 'That file could not be read. Choose a JPEG, PNG or WebP photo under 5 MB.';
  return 'The photo could not be analysed. Try again, or use a clearer photo.';
};

const Result = ({ result }) => {
  const confidence = CONFIDENCE[result.confidence] || CONFIDENCE.low;
  return (
    <div>
      <p className="eyebrow">Identified as</p>
      <h2 className="mt-1 break-words text-xl font-semibold text-gray-900 dark:text-gray-50">{result.item}</h2>

      <div className="mt-3 flex flex-wrap gap-2">
        <Badge>{result.wasteType}</Badge>
        <Badge tone={result.recyclable ? 'success' : 'warning'}>{result.recyclable ? 'Recyclable' : 'Not recyclable'}</Badge>
        <Badge tone={confidence.tone}>{confidence.label}</Badge>
      </div>

      <h3 className="mt-5 text-sm font-semibold text-gray-900 dark:text-gray-100">How to dispose of it</h3>
      <p className="mt-1 text-sm leading-relaxed text-gray-700 dark:text-gray-300">{result.disposal}</p>

      {result.upcyclingIdea && (
        <div className="mt-4 flex gap-3 rounded-lg border border-gray-200 bg-gray-50 p-3.5 dark:border-gray-800 dark:bg-gray-950">
          <LuLightbulb className="mt-0.5 h-4 w-4 shrink-0 text-gray-500 dark:text-gray-400" aria-hidden="true" />
          <div className="min-w-0">
            <p className="text-sm font-semibold text-gray-900 dark:text-gray-100">Upcycling idea</p>
            <p className="mt-0.5 text-sm leading-relaxed text-gray-700 dark:text-gray-300">{result.upcyclingIdea}</p>
          </div>
        </div>
      )}

      <div className="mt-5 flex flex-wrap gap-2">
        <Button as={Link} to={SCHEDULE_PATH} state={{ wasteType: result.wasteType }} icon={LuCalendarPlus}>
          Schedule pickup
        </Button>
        <Button as={Link} to={MARKETPLACE_PATH} variant="secondary" icon={LuShoppingBag}>
          Browse marketplace
        </Button>
      </div>

      <p className="mt-4 text-xs text-gray-500 dark:text-gray-400">
        This result is generated by AI from your photo and can be wrong. Check how hazardous items must be handled before disposing of them.
      </p>
    </div>
  );
};

// Photograph an item to find out what kind of waste it is, whether it can be
// recycled and how to dispose of it. Unavailable until the operator turns the
// feature on for the deployment.
const WasteScanner = () => {
  const [availability, setAvailability] = useState('loading'); // loading | enabled | disabled
  const [file, setFile] = useState(null);
  const [previewUrl, setPreviewUrl] = useState(null);
  const [result, setResult] = useState(null);
  const [scanning, setScanning] = useState(false);
  const inputRef = useRef(null);

  useEffect(() => {
    let active = true;
    apiAiStatus()
      .then(({ data }) => { if (active) setAvailability(data?.enabled ? 'enabled' : 'disabled'); })
      .catch(() => { if (active) setAvailability('disabled'); });
    return () => { active = false; };
  }, []);

  useEffect(() => () => { if (previewUrl) URL.revokeObjectURL(previewUrl); }, [previewUrl]);

  const choosePhoto = () => inputRef.current?.click();

  const onPickFile = (e) => {
    const picked = e.target.files?.[0];
    e.target.value = '';
    if (!picked) return;
    if (!ACCEPTED_TYPES.includes(picked.type)) {
      toast.error('Choose a JPEG, PNG or WebP photo.');
      return;
    }
    if (picked.size > MAX_BYTES) {
      toast.error('That photo is larger than 5 MB. Choose a smaller one.');
      return;
    }
    setFile(picked);
    setResult(null);
    setPreviewUrl(URL.createObjectURL(picked));
  };

  const scan = async () => {
    if (!file || scanning) return;
    setScanning(true);
    setResult(null);
    try {
      const { data } = await apiClassifyWaste(file);
      setResult(data);
    } catch (error) {
      // 503 means the feature was switched off since the page loaded.
      if (error?.response?.status === 503) setAvailability('disabled');
      else toast.error(scanError(error));
    } finally {
      setScanning(false);
    }
  };

  return (
    <div className="page">
      <PageHeader
        title="Waste scanner"
        description="Photograph an item to find out what it is, whether it can be recycled and how to dispose of it."
      />

      {availability === 'loading' && (
        <div className="grid items-start gap-6 md:grid-cols-2" aria-hidden="true">
          <Card className="p-5"><Skeleton className="h-64 w-full" /></Card>
          <Card className="p-5">
            <Skeleton className="h-3 w-24" />
            <Skeleton className="mt-3 h-6 w-48 max-w-full" />
            <Skeleton className="mt-5 h-4 w-full" />
            <Skeleton className="mt-2 h-4 w-2/3" />
          </Card>
        </div>
      )}

      {availability === 'disabled' && (
        <Card>
          <EmptyState
            icon={LuScanLine}
            title="The scanner has not been switched on yet"
            description="Photo analysis is not available on this service at the moment. You can still schedule a pickup and choose the waste type yourself."
            action={<Button as={Link} to={SCHEDULE_PATH} icon={LuCalendarPlus}>Schedule pickup</Button>}
          />
        </Card>
      )}

      {availability === 'enabled' && (
        <div className="grid items-start gap-6 md:grid-cols-2">
          <Card className="p-5">
            <input
              ref={inputRef}
              type="file"
              accept={ACCEPTED_TYPES.join(',')}
              onChange={onPickFile}
              className="hidden"
              tabIndex={-1}
            />
            {previewUrl ? (
              <>
                <img src={previewUrl} alt="The photo you chose" className="h-64 w-full rounded-lg object-cover" />
                <div className="mt-4 flex flex-wrap gap-2">
                  <Button icon={LuScanLine} loading={scanning} onClick={scan}>
                    {scanning ? 'Analysing photo' : 'Identify item'}
                  </Button>
                  <Button variant="secondary" icon={LuRefreshCw} disabled={scanning} onClick={choosePhoto}>
                    Choose another photo
                  </Button>
                </div>
              </>
            ) : (
              <button
                type="button"
                onClick={choosePhoto}
                className="flex h-64 w-full flex-col items-center justify-center gap-2 rounded-lg border-2 border-dashed border-gray-300 px-4 text-center transition-colors hover:border-brand-600 hover:bg-gray-50 dark:border-gray-700 dark:hover:border-brand-400 dark:hover:bg-gray-800/50"
              >
                <LuCamera className="h-6 w-6 text-gray-500 dark:text-gray-400" aria-hidden="true" />
                <span className="text-sm font-semibold text-gray-900 dark:text-gray-100">Take or choose a photo</span>
                <span className="text-xs text-gray-500 dark:text-gray-400">JPEG, PNG or WebP, up to 5 MB</span>
              </button>
            )}
          </Card>

          <Card className="p-5" aria-live="polite" aria-busy={scanning}>
            {scanning && (
              <div aria-hidden="true">
                <Skeleton className="h-3 w-24" />
                <Skeleton className="mt-3 h-6 w-48 max-w-full" />
                <Skeleton className="mt-4 h-5 w-56 max-w-full rounded-full" />
                <Skeleton className="mt-5 h-4 w-full" />
                <Skeleton className="mt-2 h-4 w-5/6" />
                <Skeleton className="mt-2 h-4 w-2/3" />
              </div>
            )}
            {!scanning && result && <Result result={result} />}
            {!scanning && !result && (
              <EmptyState
                icon={LuScanLine}
                title="No result yet"
                description={file ? 'Select "Identify item" to analyse your photo.' : 'Add a photo and the result will appear here.'}
                className="py-10"
              />
            )}
          </Card>
        </div>
      )}
    </div>
  );
};

export default WasteScanner;
